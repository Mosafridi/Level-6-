    private void NewBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_NewBTNActionPerformed
        try {
        int balanceValue = Integer.parseInt(BalanceField.getText());

        SwingArray.newstaff(
            IDField.getText(),
            NameField.getText(),
            PinSlider.getValue(),
            AccountComboBox.getSelectedItem().toString(),
            balanceValue,
            EmailField.getText(),
            CountyComboBox.getSelectedItem().toString(),
            AddressField.getText(),
            NumberField.getText()
        );

        //  clear fields after adding new staff
        IDField.setText(null);
        NameField.setText(null);
        PinSlider.setValue(0);
        BalanceField.setText(null);
        EmailField.setText(null);
        CountyComboBox.setSelectedIndex(0);
        AddressField.setText(null);
        NumberField.setText(null);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(null, "Please enter a valid balance value.");
    }

    }//GEN-LAST:event_NewBTNActionPerformed


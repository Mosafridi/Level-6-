    private void IDFieldKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_IDFieldKeyPressed
         int key = evt.getKeyCode();
        if ((key >= KeyEvent.VK_0 && key <= KeyEvent.VK_9) || (key == KeyEvent.VK_BACK_SPACE)){ //||=or
            IDField.setEditable(true);
        }else{
            IDField.setEditable(false);
            JOptionPane.showMessageDialog(null,"Standard Keyboard Numbers Only!");
        }//end if-else
        
    }//GEN-LAST:event_IDFieldKeyPressed

    private void NameFieldKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_NameFieldKeyPressed
         int key = evt.getKeyCode();
        if ((key >= KeyEvent.VK_A && key <= KeyEvent.VK_Z) || (key == KeyEvent.VK_BACK_SPACE)){ //||=or
            NameField.setEditable(true);
        }else{
            NameField.setEditable(false);
            JOptionPane.showMessageDialog(null,"Standard Lowercase Keyboard Letters Only!");
        }
    }//GEN-LAST:event_NameFieldKeyPressed

